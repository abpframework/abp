    public override async Task GenerateProxyAsync(GenerateProxyArgs args)
    {
        CheckWorkDirectory(args.WorkDirectory);
        CheckFolder(args.Folder);

        if (args.CommandName == RemoveProxyCommand.Name)
        {
            var folder = args.Folder.IsNullOrWhiteSpace() ? ProxyDirectory : args.Folder;
            var folderPath = Path.Combine(args.WorkDirectory, folder);

            if (Directory.Exists(folderPath))
            {
                Directory.Delete(folderPath, true);
            }

            Logger.LogInformation($"Delete {GetLoggerOutputPath(folderPath, args.WorkDirectory)}");
            return;
        }

        var applicationApiDescriptionModel = await GetApplicationApiDescriptionModelAsync(args, new ApplicationApiDescriptionModelRequestDto
        {
            IncludeTypes = !args.WithoutContracts
        });

        _ambiguousTypeNames = GetAmbiguousTypeNames(applicationApiDescriptionModel);

        foreach (var controller in applicationApiDescriptionModel.Modules.Values.SelectMany(x => x.Controllers.Values).Where(ShouldGenerateController))
        {
            await GenerateClassFileAsync(args, controller);
        }

        if (!args.WithoutContracts)
        {
            await GenerateDtoFileAsync(args, applicationApiDescriptionModel);
        }

        await CreateJsonFile(args, applicationApiDescriptionModel);

        await RemoveStaleFilesAsync(args);
    }

    protected override ServiceType? GetDefaultServiceType(GenerateProxyArgs args)
    {
        return ServiceType.All;
    }

    private async Task CreateJsonFile(GenerateProxyArgs args, ApplicationApiDescriptionModel applicationApiDescriptionModel)
    {
        var directory = GetProxyDirectory(args);
        DirectoryHelper.CreateIfNotExists(directory);

        var filePath = Path.Combine(directory, $"{args.Module}{GeneratedJsonFileSuffix}");
        using (var writer = new StreamWriter(filePath))
        {
            await writer.WriteAsync(JsonSerializer.Serialize(applicationApiDescriptionModel, indented: true));
        }
    }

    private async Task GenerateClassFileAsync(
        GenerateProxyArgs args,
        ControllerApiDescriptionModel controllerApiDescription)
    {
        var folder = GetClassFolder(args, controllerApiDescription);

        var appServiceTypeFullName = controllerApiDescription.Interfaces.Last().Type;
        var appServiceTypeName = appServiceTypeFullName.Split('.').Last();
        var clientProxyName = $"{controllerApiDescription.ControllerName}ClientProxy";
        var rootNamespace = $"{GetTypeNamespace(controllerApiDescription.Type)}";

        var classTemplateEmptyPart = new StringBuilder(ClassTemplateEmptyPart);
        classTemplateEmptyPart.Replace(ClassNamePlaceholder, clientProxyName);
        classTemplateEmptyPart.Replace(NamespacePlaceholder, rootNamespace);

        var filePath = Path.Combine(args.WorkDirectory, folder, $"{clientProxyName}.cs");
        DirectoryHelper.CreateIfNotExists(Path.GetDirectoryName(filePath)!);
        if (!File.Exists(filePath))
        {
            using (var writer = new StreamWriter(filePath))
            {
                await writer.WriteAsync(classTemplateEmptyPart.ToString());
            }

            Logger.LogInformation($"Create {GetLoggerOutputPath(filePath, args.WorkDirectory)}");
        }

        var classTemplate = new StringBuilder(ClassTemplate);

        var classUsingNamespaceList = new List<string>(ClassUsingNamespaceList)
        {
            $"using {GetTypeNamespace(appServiceTypeFullName)};"
        };

        if (!controllerApiDescription.IsIntegrationService)
        {
            classTemplate.Replace($"{Environment.NewLine}[IntegrationService]", string.Empty);
        }

        classTemplate.Replace(ClassNamePlaceholder, clientProxyName);
        classTemplate.Replace(NamespacePlaceholder, rootNamespace);
        classTemplate.Replace(ServiceInterfacePlaceholder, appServiceTypeName);

        foreach (var action in controllerApiDescription.Actions.Values.Where(x => ShouldGenerateMethod(appServiceTypeFullName, x)))
        {
            GenerateClassMethod(action, classTemplate, classUsingNamespaceList);
        }

        classTemplate.Replace($"{UsingPlaceholder}", string.Join(Environment.NewLine, classUsingNamespaceList.Distinct().OrderBy(x => x).Select(x => x)));
        classTemplate.Replace($"{Environment.NewLine}{Environment.NewLine}    {MethodPlaceholder}", string.Empty).Replace(MethodPlaceholder, string.Empty);

        filePath = Path.Combine(args.WorkDirectory, folder, $"{clientProxyName}.Generated.cs");
        DirectoryHelper.CreateIfNotExists(Path.GetDirectoryName(filePath)!);
        using (var writer = new StreamWriter(filePath))
        {
            await writer.WriteAsync(classTemplate.ToString());
            Logger.LogInformation($"Create {GetLoggerOutputPath(filePath, args.WorkDirectory)}");
        }

        if (!args.WithoutContracts)
        {
            var interfaceTemplate = new StringBuilder(InterfaceTemplate);

            interfaceTemplate.Replace(ServiceInterfacePlaceholder, appServiceTypeName);

            var @interface = controllerApiDescription.Interfaces.Last();

            var interfaceUsingNamespaceList = new List<string>(InterfaceUsingNamespaceList)
            {
                $"using {GetTypeNamespace(appServiceTypeFullName)};"
            };

            foreach (var method in @interface.Methods)
            {
                GenerateInterfaceMethod(method, interfaceTemplate, interfaceUsingNamespaceList);
            }

            interfaceTemplate.Replace($"{UsingPlaceholder}", string.Join(Environment.NewLine, interfaceUsingNamespaceList.Distinct().OrderBy(x => x).Select(x => x)));
            interfaceTemplate.Replace($"{Environment.NewLine}{Environment.NewLine}    {MethodPlaceholder}", string.Empty);
            interfaceTemplate.Replace(NamespacePlaceholder, rootNamespace);

            filePath = Path.Combine(args.WorkDirectory, folder, $"{appServiceTypeName}.cs");
            DirectoryHelper.CreateIfNotExists(Path.GetDirectoryName(filePath)!);
            using (var writer = new StreamWriter(filePath))
            {
                await writer.WriteAsync(interfaceTemplate.ToString());
                Logger.LogInformation($"Create {GetLoggerOutputPath(filePath, args.WorkDirectory)}");
            }
        }
    }

    private void GenerateClassMethod(
        ActionApiDescriptionModel action,
        StringBuilder clientProxyBuilder,
        List<string> usingNamespaceList)
    {
        var methodBuilder = new StringBuilder();
        var returnTypeName = GetTypeReference(action.ReturnValue.Type, usingNamespaceList);
        if (action.Name.EndsWith("Async"))
        {
            GenerateAsyncClassMethod(action, returnTypeName, methodBuilder, usingNamespaceList);
        }
        else
        {
            GenerateSyncClassMethod(action, returnTypeName, methodBuilder, usingNamespaceList);
        }

        clientProxyBuilder.Replace(MethodPlaceholder, $"{methodBuilder}{Environment.NewLine}    {MethodPlaceholder}");
    }

    private void GenerateSyncClassMethod(ActionApiDescriptionModel action, string returnTypeName, StringBuilder methodBuilder, List<string> usingNamespaceList)
    {
        methodBuilder.AppendLine($"public virtual {returnTypeName} {action.Name}(<args>)");

        foreach (var parameter in action.Parameters.GroupBy(x => x.Name).Select(x => x.First()))
        {
            methodBuilder.Replace("<args>", $"{GetTypeReference(parameter.Type, usingNamespaceList)} {parameter.Name}, <args>");
        }

        methodBuilder.Replace("<args>", string.Empty);
        methodBuilder.Replace(", )", ")");

        methodBuilder.AppendLine("    {");
        methodBuilder.AppendLine("        //Client Proxy does not support the synchronization method, you should always use asynchronous methods as a best practice");
        methodBuilder.AppendLine("        throw new System.NotImplementedException(); ");
        methodBuilder.AppendLine("    }");
    }

    private void GenerateAsyncClassMethod(
        ActionApiDescriptionModel action,
        string returnTypeName,
        StringBuilder methodBuilder,
        List<string> usingNamespaceList)
    {
        var isAsyncEnumerable = returnTypeName.StartsWith("IAsyncEnumerable<");
        var asyncEnumerableTypeName = isAsyncEnumerable
            ? returnTypeName.Substring("IAsyncEnumerable<".Length, returnTypeName.Length - "IAsyncEnumerable<".Length - 1)
            : null;

        var returnSign = isAsyncEnumerable ? returnTypeName : returnTypeName == "void" ? "Task" : $"Task<{returnTypeName}>";

        methodBuilder.AppendLine(isAsyncEnumerable
            ? $"public virtual {returnSign} {action.Name}(<args>)"
            : $"public virtual async {returnSign} {action.Name}(<args>)");

        foreach (var parameter in action.ParametersOnMethod)
        {
            methodBuilder.Replace("<args>", $"{GetTypeReference(parameter.Type, usingNamespaceList)} {parameter.Name}, <args>");
        }

        methodBuilder.Replace("<args>", string.Empty);
        methodBuilder.Replace(", )", ")");

        methodBuilder.AppendLine("    {");

        var argsTemplate = "new ClientProxyRequestTypeValue" +
                   $"{Environment.NewLine}        {{<args>" +
                   $"{Environment.NewLine}        }}";

        var args = action.ParametersOnMethod.Any() ? argsTemplate : string.Empty;

        methodBuilder.AppendLine(isAsyncEnumerable
            ? $"        return RequestAsyncEnumerable<{asyncEnumerableTypeName}>(nameof({action.Name}), {args});"
            : returnTypeName == "void"
                ? $"        await RequestAsync(nameof({action.Name}), {args});"
                : $"        return await RequestAsync<{returnTypeName}>(nameof({action.Name}), {args});");

        foreach (var parameter in action.ParametersOnMethod)
        {
            methodBuilder.Replace("<args>", $"{Environment.NewLine}            {{ typeof({GetTypeReference(parameter.Type)}), {parameter.Name} }},<args>");
        }

        methodBuilder.Replace(",<args>", string.Empty);
        methodBuilder.Replace(", )", ")");
        methodBuilder.AppendLine("    }");
    }

    private void GenerateInterfaceMethod(InterfaceMethodApiDescriptionModel action, StringBuilder clientProxyBuilder, List<string> usingNamespaceList)
    {
        var methodBuilder = new StringBuilder();

        var returnTypeName = GetTypeReference(action.ReturnValue.Type, usingNamespaceList);

        if (action.Name.EndsWith("Async"))
        {
            GenerateAsyncInterfaceMethod(action, returnTypeName, methodBuilder, usingNamespaceList);
        }
        else
        {
            GenerateSyncInterfaceMethod(action, returnTypeName, methodBuilder, usingNamespaceList);
        }

        clientProxyBuilder.Replace(MethodPlaceholder, $"{methodBuilder}{Environment.NewLine}    {MethodPlaceholder}");
    }

    private void GenerateSyncInterfaceMethod(InterfaceMethodApiDescriptionModel action, string returnTypeName, StringBuilder methodBuilder, List<string> usingNamespaceList)
    {
        methodBuilder.AppendLine($"public {returnTypeName} {action.Name}(<args>)");

        foreach (var parameter in action.ParametersOnMethod.GroupBy(x => x.Name).Select(x => x.First()))
        {
            methodBuilder.Replace("<args>", $"{GetTypeReference(parameter.Type, usingNamespaceList)} {parameter.Name}, <args>");
        }

        if (action.ParametersOnMethod.Count == 0)
        {
            methodBuilder.Replace("(<args>)", "(<args>);");
        }

        methodBuilder.Replace("<args>", string.Empty);
        methodBuilder.Replace(", )", ");");
    }

    private void GenerateAsyncInterfaceMethod(InterfaceMethodApiDescriptionModel action, string returnTypeName, StringBuilder methodBuilder, List<string> usingNamespaceList)
    {
        var returnSign = returnTypeName == "void" ? "Task" : $"Task<{returnTypeName}>";

        methodBuilder.AppendLine($"{returnSign} {action.Name}(<args>)");

        foreach (var parameter in action.ParametersOnMethod)
        {
            methodBuilder.Replace("<args>", $"{GetTypeReference(parameter.Type, usingNamespaceList)} {parameter.Name}, <args>");
        }

        if (action.ParametersOnMethod.Count == 0)
        {
            methodBuilder.Replace("(<args>)", "(<args>);");
        }

        methodBuilder.Replace("<args>", string.Empty);
        methodBuilder.Replace(", )", ");");
    }

    private static bool ShouldGenerateController(ControllerApiDescriptionModel controller)
    {
        return controller.Interfaces.Any() && ServicePostfixes.Any(x => controller.Interfaces.Last().Type.EndsWith(x));
    }

    private bool ShouldGenerateMethod(string appServiceTypeName, ActionApiDescriptionModel action)
    {
        return action.ImplementFrom.StartsWith(AppServicePrefix) ||
               action.ImplementFrom.StartsWith(appServiceTypeName) ||
               IsAppServiceInterface(GetRealTypeName(action.ImplementFrom));
    }

    protected virtual List<string> GetTypesToGenerate(ApplicationApiDescriptionModel applicationApiDescriptionModel)
    {
        var types = new HashSet<string>();
        var pendingTypeKeys = new Queue<string>(GetSignatureTypeNames(applicationApiDescriptionModel).SelectMany(GetReferencedTypeKeys));
        while (pendingTypeKeys.Count > 0)
        {
            var typeKey = pendingTypeKeys.Dequeue();
            if (types.Contains(typeKey) || !applicationApiDescriptionModel.Types.ContainsKey(typeKey) || IsClientProvidedType(typeKey))
            {
                continue;
            }

            types.Add(typeKey);

            var type = applicationApiDescriptionModel.Types[typeKey];
            var referencedTypeKeys = GetReferencedTypeKeys(type.BaseType)
                .Concat((type.Properties ?? []).SelectMany(x => GetReferencedTypeKeys(x.Type)));
            foreach (var referencedTypeKey in referencedTypeKeys)
            {
                pendingTypeKeys.Enqueue(referencedTypeKey);
            }
        }

        return types.OrderBy(x => x).ToList();
    }

    private List<string> GetSignatureTypeNames(ApplicationApiDescriptionModel applicationApiDescriptionModel)
    {
        var signatureTypeNames = new List<string>();
        foreach (var controller in applicationApiDescriptionModel.Modules.Values.SelectMany(x => x.Controllers.Values).Where(ShouldGenerateController))
        {
            var appServiceType = controller.Interfaces.Last();
            foreach (var method in appServiceType.Methods)
            {
                signatureTypeNames.AddRange(method.ParametersOnMethod.Select(x => x.Type));
                signatureTypeNames.Add(method.ReturnValue.Type);
            }

            foreach (var action in controller.Actions.Values.Where(x => ShouldGenerateMethod(appServiceType.Type, x)))
            {
                signatureTypeNames.AddRange(action.ParametersOnMethod.Select(x => x.Type));
                signatureTypeNames.Add(action.ReturnValue.Type);
            }
        }

        return signatureTypeNames;
    }

    private static IEnumerable<string> GetReferencedTypeKeys(string typeName)
    {
        return ParseTypeNames(typeName).Select(x => x.GenericArgumentCount == 0
            ? x.Name
            : $"{x.Name}<{Enumerable.Range(0, x.GenericArgumentCount).Select(i => $"T{i}").JoinAsString(",")}>");
    }

    private static IEnumerable<(string Name, int GenericArgumentCount)> ParseTypeNames(string typeName)
    {
        if (typeName.IsNullOrWhiteSpace())
        {
            yield break;
        }

        var index = 0;
        while (index < typeName.Length)
        {
            if (!IsTypeNameChar(typeName[index]))
            {
                index++;
                continue;
            }

            var start = index;
            while (index < typeName.Length && IsTypeNameChar(typeName[index]))
            {
                index++;
            }

            var name = typeName.Substring(start, index - start);
            if (!name.Contains('.'))
            {
                continue;
            }

            var genericArgumentCount = index < typeName.Length && typeName[index] == '<'
                ? GetGenericArgumentCount(typeName, index)
                : 0;

            yield return (name, genericArgumentCount);
        }
    }

    private static bool IsTypeNameChar(char c)
    {
        return char.IsLetterOrDigit(c) || c == '_' || c == '.' || c == '+';
    }

    private static int GetGenericArgumentCount(string typeName, int openingBracketIndex)
    {
        var depth = 0;
        var count = 1;
        for (var i = openingBracketIndex; i < typeName.Length; i++)
        {
            switch (typeName[i])
            {
                case '<':
                    depth++;
                    break;
                case '>':
                    if (--depth == 0)
                    {
                        return count;
                    }
                    break;
                case ',' when depth == 1:
                    count++;
                    break;
            }
        }

        return count;
    }

    private static bool IsClientProvidedType(string typeKey)
    {
        return ClientProvidedTypeNamespacePrefixes.Any(typeKey.StartsWith);
    }

    private Dictionary<string, string> GetDtoFilePaths(GenerateProxyArgs args, ApplicationApiDescriptionModel applicationApiDescriptionModel)
    {
        var typeNames = GetTypesToGenerate(applicationApiDescriptionModel)
            .ToDictionary(x => x, x => GetDtoTypeName(x, applicationApiDescriptionModel.Types[x]));

        var filePaths = typeNames.ToDictionary(x => x.Key, x => GetDtoFilePath(args, x.Value, false, false));
        foreach (var sameFileTypes in filePaths.GroupBy(x => x.Value).Where(x => x.Count() > 1).ToList())
        {
            foreach (var typeKey in sameFileTypes.Select(x => x.Key).Where(x => x.Contains('<')))
            {
                filePaths[typeKey] = GetDtoFilePath(args, typeNames[typeKey], true, false);
            }
        }

        foreach (var sameFileTypes in filePaths.GroupBy(x => x.Value).Where(x => x.Count() > 1).ToList())
        {
            foreach (var typeKey in sameFileTypes.Select(x => x.Key))
            {
                filePaths[typeKey] = GetDtoFilePath(args, typeNames[typeKey], true, true);
            }
        }

        return filePaths;
    }

    private static string GetDtoTypeName(string typeKey, TypeApiDescriptionModel type)
    {
        return type.GenericArguments.IsNullOrEmpty()
            ? typeKey
            : $"{typeKey.Left(typeKey.IndexOf('<'))}<{type.GenericArguments.JoinAsString(",")}>";
    }

    private static string GetDtoFilePath(GenerateProxyArgs args, string genericTypeName, bool includeGenericArguments, bool includeNamespace)
    {
        var folder = args.Folder.IsNullOrWhiteSpace()
            ? ProxyDirectory + Path.DirectorySeparatorChar + GetTypeNamespace(genericTypeName)
                .Replace(".", Path.DirectorySeparatorChar.ToString())
            : args.Folder;

        var realTypeName = GetRealTypeName(genericTypeName);
        var dtoFileName = includeGenericArguments
            ? realTypeName.Replace('<', '{').Replace('>', '}').Replace(" ", string.Empty)
            : realTypeName.Split("<")[0];

        if (includeNamespace)
        {
            dtoFileName = $"{GetTypeNamespace(genericTypeName.Split('<')[0])}.{dtoFileName}";
        }

        return Path.Combine(args.WorkDirectory, folder, $"{dtoFileName}.cs");
    }

    private async Task GenerateDtoFileAsync(GenerateProxyArgs args, ApplicationApiDescriptionModel applicationApiDescriptionModel)
    {
        var filePaths = GetDtoFilePaths(args, applicationApiDescriptionModel);

        foreach (var type in applicationApiDescriptionModel.Types.Where(x => filePaths.ContainsKey(x.Key)))
        {
            var dto = new StringBuilder(DtoTemplate);
            var dtoUsingNamespaceList = new List<string>(DtoUsingNamespaceList)
            {
                $"using {GetTypeNamespace(type.Key)};"
            };

            var genericTypeName = GetDtoTypeName(type.Key, type.Value);

            dto.Replace(NamespacePlaceholder, GetTypeNamespace(genericTypeName));
            dto.Replace(DtoClassNamePlaceholder, type.Value.IsEnum
                ? "enum " + GetRealTypeName(genericTypeName, dtoUsingNamespaceList)
                : "class " + GetRealTypeName(genericTypeName, dtoUsingNamespaceList) +
                  (type.Value.BaseType.IsNullOrEmpty()
                      ? ""
                      : $" : {GetTypeReference(type.Value.BaseType, dtoUsingNamespaceList)}"));
            var properties = new StringBuilder();
            if (type.Value.IsEnum)
            {
                for (var i = 0; i < type.Value.EnumNames.Length; i++)
                {
                    var enumName = type.Value.EnumNames[i];
                    properties.Append($"{enumName} = {type.Value.EnumValues[i]}");

                    if (i < type.Value.EnumNames.Length - 1)
                    {
                        properties.Append($",");
                        properties.AppendLine();
                        properties.Append("    ");
                    }
                }
            }
            else
            {
                if (!type.Value.Properties.IsNullOrEmpty())
                {
                    for (var i = 0; i < type.Value.Properties.Length; i++)
                    {
                        var property = type.Value.Properties[i];
                        properties.Append("public ");
                        properties.Append(GetTypeReference(property.Type, dtoUsingNamespaceList));
                        properties.Append($" {property.Name}");
                        properties.Append(" { get; set; }");
                        if (i < type.Value.Properties.Length - 1)
                        {
                            properties.AppendLine();
                            properties.AppendLine();
                            properties.Append("    ");
                        }
                    }
                }
            }

            dto.Replace($"{UsingPlaceholder}", string.Join(Environment.NewLine, dtoUsingNamespaceList.Distinct().OrderBy(x => x).Select(x => x)));
            dto.Replace(PropertyPlaceholder, properties.ToString());

            var filePath = filePaths[type.Key];
            Directory.CreateDirectory(Path.GetDirectoryName(filePath));
            using (var writer = new StreamWriter(filePath))
            {
                await writer.WriteAsync(dto.ToString());
                Logger.LogInformation($"Create {GetLoggerOutputPath(filePath, args.WorkDirectory)}");
            }
        }
    }

    protected virtual async Task RemoveStaleFilesAsync(GenerateProxyArgs args)
    {
        var directory = Path.GetFullPath(GetProxyDirectory(args));
        if (!Directory.Exists(directory))
        {
            return;
        }

        // The file system is case insensitive on Windows and macOS, an existing file keeps its casing when it is overwritten.
        var pathComparison = RuntimeInformation.IsOSPlatform(OSPlatform.Linux) ? StringComparison.Ordinal : StringComparison.OrdinalIgnoreCase;
        var expectedFiles = new HashSet<string>(pathComparison == StringComparison.Ordinal ? StringComparer.Ordinal : StringComparer.OrdinalIgnoreCase);
        foreach (var jsonFile in Directory.GetFiles(directory, $"*{GeneratedJsonFileSuffix}"))
        {
            ApplicationApiDescriptionModel applicationApiDescriptionModel;
            try
            {
                applicationApiDescriptionModel = JsonSerializer.Deserialize<ApplicationApiDescriptionModel>(await FileHelper.ReadAllTextAsync(jsonFile));
            }
            catch (Exception ex)
            {
                Logger.LogWarning($"Skipped removing stale files, {GetLoggerOutputPath(jsonFile, args.WorkDirectory)} could not be read: {ex.Message}");
                return;
            }

            // Other modules may have been generated with or without contracts, so their service interfaces are always kept.
            var isCurrentModule = Path.GetFileName(jsonFile).Equals($"{args.Module}{GeneratedJsonFileSuffix}", StringComparison.OrdinalIgnoreCase);
            var withContracts = !isCurrentModule || !args.WithoutContracts;
            expectedFiles.AddIfNotContains(GetGeneratedFilePaths(args, applicationApiDescriptionModel, withContracts).Select(Path.GetFullPath));
        }

        var otherProxyDirectories = Directory.GetFiles(directory, $"*{GeneratedJsonFileSuffix}", SearchOption.AllDirectories)
            .Select(x => Path.GetDirectoryName(Path.GetFullPath(x))!)
            .Where(x => !string.Equals(x, directory, pathComparison))
            .Distinct()
            .Select(x => x + Path.DirectorySeparatorChar)
            .ToList();

        foreach (var file in Directory.GetFiles(directory, "*.cs", SearchOption.AllDirectories).Select(Path.GetFullPath))
        {
            if (expectedFiles.Contains(file) ||
                otherProxyDirectories.Any(x => file.StartsWith(x, pathComparison)) ||
                File.ReadLines(file).FirstOrDefault() != GeneratedFileHeader)
            {
                continue;
            }

            File.Delete(file);
            Logger.LogInformation($"Delete {GetLoggerOutputPath(file, args.WorkDirectory)}");
        }
    }

    private IEnumerable<string> GetGeneratedFilePaths(GenerateProxyArgs args, ApplicationApiDescriptionModel applicationApiDescriptionModel, bool withContracts)
    {
        foreach (var controller in applicationApiDescriptionModel.Modules.Values.SelectMany(x => x.Controllers.Values).Where(ShouldGenerateController))
        {
            var folder = GetClassFolder(args, controller);
            yield return Path.Combine(args.WorkDirectory, folder, $"{controller.ControllerName}ClientProxy.Generated.cs");

            if (withContracts)
            {
                yield return Path.Combine(args.WorkDirectory, folder, $"{controller.Interfaces.Last().Type.Split('.').Last()}.cs");
            }
        }

        if (withContracts && applicationApiDescriptionModel.Types != null)
        {
            foreach (var filePath in GetDtoFilePaths(args, applicationApiDescriptionModel).Values)
            {
                yield return filePath;
            }
        }
    }

    private static string GetProxyDirectory(GenerateProxyArgs args)
    {
        return Path.Combine(args.WorkDirectory, args.Folder.IsNullOrWhiteSpace() ? ProxyDirectory : args.Folder);
    }

    private static string GetClassFolder(GenerateProxyArgs args, ControllerApiDescriptionModel controller)
    {
        return args.Folder.IsNullOrWhiteSpace()
            ? ProxyDirectory + Path.DirectorySeparatorChar + GetTypeNamespace(controller.Type).Replace(".", Path.DirectorySeparatorChar.ToString())
            : args.Folder;
    }

    private static bool IsAppServiceInterface(string typeName)
    {
        return typeName.StartsWith("I") && ServicePostfixes.Any(typeName.Contains);
    }

    private static string GetTypeNamespace(string typeFullName)
    {
        return typeFullName.Substring(0, typeFullName.LastIndexOf('.'));
    }

    private string GetTypeReference(string typeName, List<string> usingNamespaceList = null)
    {
        return GetRealTypeName(typeName, usingNamespaceList, _ambiguousTypeNames);
    }

    private HashSet<string> GetAmbiguousTypeNames(ApplicationApiDescriptionModel applicationApiDescriptionModel)
    {
        // Types are not requested with --without-contracts, so the names used by the signatures are collected as well.
        var typeNames = (applicationApiDescriptionModel.Types?.Keys ?? [])
            .Select(x => x.Split('<')[0])
            .Concat(GetSignatureTypeNames(applicationApiDescriptionModel).SelectMany(x => ParseTypeNames(x).Select(t => t.Name)))
            .Distinct()
            .GroupBy(x => x.Split('.').Last())
            .Where(x => x.Count() > 1)
            .SelectMany(x => x);

        return new HashSet<string>(typeNames);
    }

    private static string GetRealTypeName(string typeName, List<string> usingNamespaceList = null, ICollection<string> ambiguousTypeNames = null)
    {
        if (typeName.StartsWith("[") && typeName.EndsWith("]"))
        {
            return GetRealTypeName(typeName.Substring(1, typeName.Length - 2), usingNamespaceList, ambiguousTypeNames) + "[]";
        }

        if (typeName.StartsWith("{") && typeName.EndsWith("}") && typeName.Contains(":"))
        {
            var dic = typeName.Substring(1, typeName.Length - 2).Split(new[] { ':' }, 2);
            var key = GetRealTypeName(dic[0], usingNamespaceList, ambiguousTypeNames);
            var value = GetRealTypeName(dic[1], usingNamespaceList, ambiguousTypeNames);
            return $"Dictionary<{key}, {value}>";
        }

        if (!typeName.Contains('.') && !typeName.Contains('<'))
        {
            return NormalizeTypeName(typeName);
        }

        if (!typeName.Contains("<"))
        {
            usingNamespaceList?.AddIfNotContains($"using {GetTypeNamespace(typeName)};");
            return NormalizeTypeName(GetShortTypeName(typeName, ambiguousTypeNames));
        }

        if(usingNamespaceList != null)
        {
            AddGenericTypeUsingNamespace(typeName, usingNamespaceList);
        }

        return Regex.Replace(typeName, @"[\w.+]+", x => x.Value.Contains('.') ? GetShortTypeName(x.Value, ambiguousTypeNames) : x.Value)
            .Replace(",", ", ");
    }

    private static string GetShortTypeName(string typeFullName, ICollection<string> ambiguousTypeNames)
    {
        return ambiguousTypeNames != null && ambiguousTypeNames.Contains(typeFullName.TrimEnd('?'))
            ? $"global::{typeFullName}"
            : typeFullName.Split(".").Last();
    }

    private static void AddGenericTypeUsingNamespace(string typeFullName, List<string> usingNamespaceList)
    {
        foreach (var typeName in ParseTypeNames(typeFullName))
        {
            usingNamespaceList.AddIfNotContains($"using {GetTypeNamespace(typeName.Name)};");
        }
    }

    private static string NormalizeTypeName(string typeName)
    {
        var nullable = string.Empty;
        if (typeName.EndsWith("?"))
        {
            typeName = typeName.TrimEnd('?');
            nullable = "?";
        }

        typeName = typeName switch
        {
            "System.Void" => "void",
            "Void" => "void",
            "System.Boolean" => "bool",
            "Boolean" => "bool",
            "System.String" => "string",
            "String" => "string",
            "System.Int32" => "int",
            "Int32" => "int",
            "System.Int64" => "long",
            "Int64" => "long",
            "System.Double" => "double",
            "Double" => "double",
            "System.Object" => "object",
            "Object" => "object",
            "System.Byte" => "byte",
            "Byte" => "byte",
            "System.Char" => "char",
            "Char" => "char",
            _ => typeName
        };

        return $"{typeName}{nullable}";
    }

    private static void CheckWorkDirectory(string directory)
    {
        if (!Directory.Exists(directory))
        {
            throw new CliUsageException("Specified directory does not exist.");
        }

        var projectFiles = Directory.GetFiles(directory, "*.csproj");
        if (!projectFiles.Any())
        {
            throw new CliUsageException("No project file(csproj) found in the directory.");
        }
    }

    private static void CheckFolder(string folder)
    {
        if (!folder.IsNullOrWhiteSpace() && Path.HasExtension(folder))
        {
            throw new CliUsageException("Option folder should be a directory.");
        }
    }
