    public override async Task GenerateProxyAsync(GenerateProxyArgs args)
    {
        CheckWorkDirectory(args.WorkDirectory);
        CheckFolder(args.Folder);

        if (args.CommandName == RemoveProxyCommand.Name)
        {
            var folder = args.Folder.IsNullOrWhiteSpace() ? ProxyDirectory : args.Folder;
            var folderPath = Path.Combine(args.WorkDirectory, folder);

            if (Directory.Exists(folderPath))
            {
                Directory.Delete(folderPath, true);
            }

            Logger.LogInformation($"Delete {GetLoggerOutputPath(folderPath, args.WorkDirectory)}");
            return;
        }

        var applicationApiDescriptionModel = await GetApplicationApiDescriptionModelAsync(args, new ApplicationApiDescriptionModelRequestDto
        {
            IncludeTypes = !args.WithoutContracts
        });

        var hasAssemblyNames = !args.WithoutContracts &&
                               applicationApiDescriptionModel.Types?.Values.Any(x => !x.AssemblyName.IsNullOrWhiteSpace()) == true;
        if (hasAssemblyNames)
        {
            LoadClientProvidedAssemblyNames(args.WorkDirectory);
        }
        else
        {
            _clientProvidedAssemblyNames = null;
        }

        if (!args.WithoutContracts && applicationApiDescriptionModel.Types?.Count > 0)
        {
            if (!hasAssemblyNames)
            {
                Logger.LogWarning("The remote service does not provide contract assembly names. Falling back to namespace based contract type detection.");
            }
            else if (_clientProvidedAssemblyNames == null)
            {
                Logger.LogWarning("Project assets are unavailable. Falling back to namespace based contract type detection.");
            }
        }

        _generatedContractTypeNamespacePrefixes = GetGeneratedContractTypeNamespacePrefixes(applicationApiDescriptionModel);
        _typesToGenerate = args.WithoutContracts
            ? new List<string>()
            : GetTypesToGenerate(applicationApiDescriptionModel);
        _generatedContractTypeNames = new HashSet<string>(_typesToGenerate
            .Select(x => ParseTypeNames(x).First().Name), StringComparer.Ordinal);
        _ambiguousTypeNames = GetAmbiguousTypeNames(applicationApiDescriptionModel, _typesToGenerate);

        foreach (var controller in applicationApiDescriptionModel.Modules.Values.SelectMany(x => x.Controllers.Values).Where(ShouldGenerateController))
        {
            await GenerateClassFileAsync(args, controller);
        }

        if (!args.WithoutContracts)
        {
            await GenerateDtoFileAsync(args, applicationApiDescriptionModel);
        }

        await CreateJsonFile(args, applicationApiDescriptionModel);
    }

    protected override ServiceType? GetDefaultServiceType(GenerateProxyArgs args)
